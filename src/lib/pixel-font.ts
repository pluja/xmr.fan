// Cyrillic letters that look like Latin ones.
for (const [cyr, lat] of Object.entries({ А: "A", В: "B", Е: "E", К: "K", М: "M", Н: "H", О: "O", Р: "P", С: "C", Т: "T", Х: "X" })) G[cyr] = G[lat];

/** Accents sit in the two rows above a capital. */
const ACCENTS: Record<string, [string, string[]]> = {
  É: ["E", ["...#.", "..#.."]],
  È: ["E", [".#...", "..#.."]],
  Ê: ["E", ["..#..", ".#.#."]],
  Á: ["A", ["...#.", "..#.."]],
  Ó: ["O", ["...#.", "..#.."]],
  Ã: ["A", [".##.#", "#..#."]],
  Õ: ["O", [".##.#", "#..#."]],
};

/** Glyph rows for a character, with two extra rows on top for accents; null if the font lacks it. */
export function glyph(ch: string): string[] | null {
  const blank = ".....";
  if (G[ch]) return [blank, blank, ...G[ch]];
  const accented = ACCENTS[ch];
  return accented ? [...accented[1], ...G[accented[0]]] : null;
}

export const hasGlyphs = (text: string) => [...text].every((ch) => glyph(ch) !== null);

/** Width in pixels of `text` at `scale`, with `gap` font pixels between letters. */
export const textWidth = (text: string, scale: number, gap = 1) => Math.max(0, [...text].length * (GLYPH_W + gap) - gap) * scale;
