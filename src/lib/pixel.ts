export type IconName = keyof typeof ICONS;

export interface PixelRect { x: number; y: number; delay: number }

// Deterministic "random" delays so builds are reproducible.
function* delays(seed: number) {
  let s = seed;
  for (;;) { s = (s * 1103515245 + 12345) & 0x7fffffff; yield (s % 600); }
}

export function layoutText(text: string, seed = 7) {
  const rnd = delays(seed);
  const rects: PixelRect[] = [];
  let x = 0;
  for (const ch of text) {
    const g = GLYPHS[ch];
    if (!g) { x += 3; continue; }
    g.forEach((row, y) => [...row].forEach((c, i) => {
      if (c === "#") rects.push({ x: x + i, y, delay: rnd.next().value as number });
    }));
    x += g[0].length + 1;
  }
  const height = Math.max(7, ...[...text].map((c) => GLYPHS[c]?.length ?? 0));
  return { width: x - 1, height, rects };
}

/** An icon's 8x8 bitmap rows ('#' = lit). */
export const iconBitmap = (name: IconName): readonly string[] => ICONS[name];

/** Single SVG path for an 8x8 icon. */
export function iconPath(name: IconName): string {
  let d = "";
  ICONS[name].forEach((row, y) => [...row].forEach((c, x) => {
    if (c === "#") d += `M${x} ${y}h1v1h-1z`;
  }));
  return d;
}
