const BASE: Record<Locale, BaseDict> = { en, es, ru, fr, pt, ja };
const DICTS = Object.fromEntries(
  LOCALES.map((l) => [l, Object.assign({}, BASE[l], ...STRING_MODULES.map((s) => s[l]))]),
) as Record<Locale, Dict>;

export function useTranslations(lang: Locale) {
  return (key: Key, vars?: Record<string, string | number>) => format(DICTS[lang][key] ?? DICTS.en[key], vars);
}

/** Strings a client script needs, as JSON for a data-strings attribute (read with readStrings). */
export const pickStrings = (lang: Locale, keys: Key[]) =>
  JSON.stringify(Object.fromEntries(keys.map((k) => [k, DICTS[lang][k]])));

/** "/tools/units" -> "/es/tools/units" (English has no prefix). */
export function localePath(lang: Locale, path = "/"): string {
  const p = path.startsWith("/") ? path : `/${path}`;
  return lang === DEFAULT_LOCALE ? p : `/${lang}${p === "/" ? "/" : p}`;
}

export const isLocale = (s: unknown): s is Locale => LOCALES.includes(s as Locale);

/* Routes live under src/pages/[...lang]/: English has no prefix, others use /<lang>/. */
export const localeParams = () =>
  LOCALES.map((lang) => ({ lang: lang === DEFAULT_LOCALE ? undefined : lang }));

export const langFromParams = (params: { lang?: string }): Locale =>
  isLocale(params.lang) ? params.lang : DEFAULT_LOCALE;
